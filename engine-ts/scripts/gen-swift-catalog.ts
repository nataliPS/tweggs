// Generates MixlingsKit/Sources/MixlingsGenome/Catalog.swift from src/catalog.ts
// so the two catalogs never drift. Usage: npm run gen:swift (also run by npm run golden)

import { writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import { CATALOG } from "../src/catalog.ts";

const here = dirname(fileURLToPath(import.meta.url));
const out = resolve(here, "../../MixlingsKit/Sources/MixlingsGenome/Catalog.swift");

const lines: string[] = [];
lines.push("// GENERATED by engine-ts/scripts/gen-swift-catalog.ts from engine-ts/src/catalog.ts.");
lines.push("// DO NOT EDIT BY HAND. Run `npm run gen:swift` in engine-ts/.");
lines.push("");
lines.push("public struct VariantDef: Codable, Equatable, Sendable {");
lines.push("    public let name: String");
lines.push("    /// 1...9, higher wins expression.");
lines.push("    public let dominance: Int");
lines.push("    /// 0 common, 1 uncommon, 2 rare, 3 legendary.");
lines.push("    public let rarity: Int");
lines.push("    public let mutationOnly: Bool");
lines.push("");
lines.push("    public init(name: String, dominance: Int, rarity: Int, mutationOnly: Bool) {");
lines.push("        self.name = name");
lines.push("        self.dominance = dominance");
lines.push("        self.rarity = rarity");
lines.push("        self.mutationOnly = mutationOnly");
lines.push("    }");
lines.push("}");
lines.push("");
lines.push("public struct GeneDef: Equatable, Sendable {");
lines.push("    public let key: String");
lines.push("    public let variants: [VariantDef]");
lines.push("}");
lines.push("");
lines.push("public enum Catalog {");
lines.push(`    public static let geneKeys: [String] = [${CATALOG.map((g) => JSON.stringify(g.key)).join(", ")}]`);
lines.push(`    public static let geneCount: Int = ${CATALOG.length}`);
lines.push("");
lines.push("    public static let genes: [GeneDef] = [");
for (const g of CATALOG) {
  lines.push(`        GeneDef(key: ${JSON.stringify(g.key)}, variants: [`);
  for (const v of g.variants) {
    lines.push(`            VariantDef(name: ${JSON.stringify(v.name)}, dominance: ${v.dominance}, rarity: ${v.rarity}, mutationOnly: ${v.mutationOnly}),`);
  }
  lines.push("        ]),");
}
lines.push("    ]");
lines.push("}");
lines.push("");

writeFileSync(out, lines.join("\n"));
console.log(`wrote ${out}`);
