"""Emit the living-world constant tables of render.py for the ports (do not hand-edit
the outputs): art/ts-port/living-tables.ts and
MixlingsKit/Sources/MixlingsArt/LivingTables.swift. Run after changing a table."""
import render as R

ROWS = ["ZZZ_ROWS", "BANG", "BOLT", "SWEAT", "SUN", "MOON", "LEAF", "FLAKE", "UMBRELLA",
        "BOTTLE", "FAN", "SUN_HAT", "BEANIE", "JUICE", "HANDLE", "CLOUD", "PICTURE", "SHELF",
        "PLANT", "LAMP", "CHESS_TABLE", "EASEL", "PAINT_POT", "BUBBLE", "TELESCOPE",
        "BREAKFAST_TABLE", "PLATE_FOOD", "EGG_PLATE", "DESK", "BIG_CLOUD", "DIZZY", "STARBURST"]
PTS = ["RAIN_DROPS", "SNOW_FLAKES", "SHEEN", "WIN_STARS", "WIN_RAIN", "WIN_SNOW",
       "YARD_CLOUDS", "YARD_TUFTS"]
TRI = ["WIND_LINES", "EASEL_DABS"]


def camel(n):
    a = n.lower().split("_")
    return a[0] + "".join(w.title() for w in a[1:])


def ts():
    o = ["// GENERATED by art/gen_tables.py from art/render.py. Do not edit.",
         "export type RGB = [number, number, number];"]
    o.append("export const LW: Record<string, RGB> = {")
    for k, v in R.LW.items():
        o.append(f'  "{k}": [{v[0]}, {v[1]}, {v[2]}],')
    o.append("};")
    for n in ROWS:
        o.append(f"export const {n}: string[] = {list(getattr(R, n))!r};".replace("'", '"'))
    o.append(f"export const EMOTES: string[][] = {R.EMOTES!r};".replace("'", '"'))
    o.append(f"export const GLYPHS: string[][] = {R.GLYPHS!r};".replace("'", '"'))
    o.append(f"export const BULBS: string[] = {R.BULBS!r};".replace("'", '"'))
    for n in PTS + TRI:
        o.append(f"export const {n}: number[][] = {[list(t) for t in getattr(R, n)]!r};")
    o.append("export const YARD_FLOWERS: [number, number, string][] = "
             + repr([list(t) for t in R.YARD_FLOWERS]).replace("'", '"') + ";")
    for n in ("ROOM", "SKY"):
        o.append(f"export const {n}: Record<string, [RGB, RGB]> = {{")
        for k, (a, b) in getattr(R, n).items():
            o.append(f'  "{k}": [[{a[0]}, {a[1]}, {a[2]}], [{b[0]}, {b[1]}, {b[2]}]],')
        o.append("};")
    o.append("export const YARD: Record<string, RGB> = {")
    for k, v in R.YARD.items():
        o.append(f'  "{k}": [{v[0]}, {v[1]}, {v[2]}],')
    o.append("};")
    for n in ("NIGHT_TINT", "CREATURE_NIGHT"):
        o.append(f"export const {n}: RGB = {list(getattr(R, n))!r};")
    o.append(f"export const JR_LOOP: number[][] = {[list(t) for t in R.JR_LOOP]!r};")
    o.append(f"export const JR_HEIGHT: number[] = {R.JR_HEIGHT!r};")
    return "\n".join(o) + "\n"


def sw_rgb(v):
    return f"RGB({v[0]}, {v[1]}, {v[2]})"


def sw_str_list(l):
    return "[" + ", ".join('"' + s + '"' for s in l) + "]"


def swift():
    o = ["// GENERATED by art/gen_tables.py from art/render.py. Do not edit.",
         "// swiftlint:disable all", ""]
    o.append("let LW: [Character: RGB] = [")
    for k, v in R.LW.items():
        o.append(f'    "{k}": {sw_rgb(v)},')
    o.append("]")
    for n in ROWS:
        o.append(f"let {n}: [String] = {sw_str_list(getattr(R, n))}")
    o.append("let EMOTES: [[String]] = [" + ", ".join(sw_str_list(e) for e in R.EMOTES) + "]")
    o.append("let GLYPHS: [[String]] = [")
    for g in R.GLYPHS:
        o.append("    " + sw_str_list(g) + ",")
    o.append("]")
    o.append("let BULBS: [Character] = [" + ", ".join(f'"{b}"' for b in R.BULBS) + "]")
    for n in PTS:
        o.append(f"let {n}: [(Int, Int)] = [" + ", ".join(f"({a}, {b})" for a, b in getattr(R, n)) + "]")
    for n in TRI:
        o.append(f"let {n}: [(Int, Int, Int)] = ["
                 + ", ".join(f"({a}, {b}, {c})" for a, b, c in getattr(R, n)) + "]")
    o.append("let YARD_FLOWERS: [(Int, Int, Character)] = ["
             + ", ".join(f'({a}, {b}, "{c}")' for a, b, c in R.YARD_FLOWERS) + "]")
    for n in ("ROOM", "SKY"):
        o.append(f"let {n}: [String: (RGB, RGB)] = [")
        for k, (a, b) in getattr(R, n).items():
            o.append(f'    "{k}": ({sw_rgb(a)}, {sw_rgb(b)}),')
        o.append("]")
    o.append("let YARD: [String: RGB] = [")
    for k, v in R.YARD.items():
        o.append(f'    "{k}": {sw_rgb(v)},')
    o.append("]")
    for n in ("NIGHT_TINT", "CREATURE_NIGHT"):
        o.append(f"let {n} = {sw_rgb(getattr(R, n))}")
    o.append("let JR_LOOP: [(Int, Int)] = [" + ", ".join(f"({a}, {b})" for a, b in R.JR_LOOP) + "]")
    o.append(f"let JR_HEIGHT: [Int] = {R.JR_HEIGHT!r}")
    return "\n".join(o) + "\n"


if __name__ == "__main__":
    open("ts-port/living-tables.ts", "w").write(ts())
    open("../MixlingsKit/Sources/MixlingsArt/LivingTables.swift", "w").write(swift())
    print("tables written")
